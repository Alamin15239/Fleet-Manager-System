const LanguageContext = createContext<LanguageContextType | undefined>(undefined)

export function translateText(key: string, language: Language): string {
  const keyedTranslation = translations[language][key as keyof typeof translations['en']]
  if (keyedTranslation) return keyedTranslation
  if (language === 'ar') {
    const exactTranslation = phraseTranslations[key]
    if (exactTranslation) return exactTranslation

    // Database enums are stored as uppercase tokens (for example IN_PROGRESS).
    // Translate only these controlled values, leaving names and free-form data alone.
    if (/^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)*$/.test(key)) {
      const enumLabel = key.replace(/_/g, ' ').toLowerCase().replace(/^./, (letter) => letter.toUpperCase())
      const enumTranslation = Object.entries(phraseTranslations).find(
        ([label]) => label.toLowerCase() === enumLabel.toLowerCase(),
      )?.[1]
      if (enumTranslation) return enumTranslation
    }

    const dynamicTranslations: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
      [/^Maximum (\d+) files allowed$/, ([, count]) => `الحد الأقصى المسموح به هو ${count} ملفات`],
      [/^File type (.+) is not supported$/, ([, type]) => `نوع الملف ${type} غير مدعوم`],
      [/^File (.+) is too large\. Maximum size is ([\d.]+)MB$/, ([, name, size]) => `حجم الملف ${name} كبير جداً. الحد الأقصى ${size} ميجابايت`],
      [/^File (.+) uploaded successfully$/, ([, name]) => `تم رفع الملف ${name} بنجاح`],
      [/^Failed: (.+)$/, ([, detail]) => `فشل: ${detail}`],
      [/^Health check completed: (.+)$/, ([, status]) => `اكتمل فحص الحالة: ${translateText(status, 'ar')}`],
      [/^Cleanup completed: (.+)$/, ([, detail]) => `اكتمل التنظيف: ${detail}`],
      [/^System check completed: (.+)$/, ([, status]) => `اكتمل فحص النظام: ${translateText(status, 'ar')}`],
      [/^Security scan completed: (\d+) issues found$/, ([, count]) => `اكتمل فحص الأمان: تم العثور على ${count} مشكلات`],
      [/^Job card (.+) created$/, ([, number]) => `تم إنشاء أمر العمل ${number}`],
      [/^Successfully created (\d+) tire\(s\)$/, ([, count]) => `تم إنشاء ${count} إطار بنجاح`],
    ]
    for (const [pattern, render] of dynamicTranslations) {
      const match = key.match(pattern)
      if (match) return render(match)
    }

    const englishKey = Object.keys(translations.en).find(
      (candidate) => translations.en[candidate as keyof typeof translations.en] === key,
    )
    if (englishKey) return translations.ar[englishKey as keyof typeof translations.ar] || key
  }
  return key
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>('en')

  useEffect(() => {
    try {
      const savedLanguage = localStorage.getItem('language') as Language
      if (savedLanguage && (savedLanguage === 'en' || savedLanguage === 'ar')) {
        setLanguage(savedLanguage)
      }
    } catch {
      // Language selection remains available when browser storage is blocked.
    }
  }, [])

  useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr'
  }, [language])

  const toggleLanguage = () => {
    const newLanguage = language === 'en' ? 'ar' : 'en'
    setLanguage(newLanguage)
    try {
      localStorage.setItem('language', newLanguage)
    } catch {
      // Apply the choice for this session even if it cannot be persisted.
    }
    document.documentElement.lang = newLanguage
    document.documentElement.dir = newLanguage === 'ar' ? 'rtl' : 'ltr'
  }

  const t = (key: string): string => translateText(key, language)

  return (
    <LanguageContext.Provider value={{ language, toggleLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider')
  }
  return context
}
